#!/usr/bin/env bash
set -euo pipefail

RUN_DIR="$(cd "$(dirname "$0")" && pwd -P)"
# shellcheck disable=SC1091
source "$RUN_DIR/RUNINFO.txt"

mkdir -p "$RUN_DIR/support" "$RUN_DIR/logs"
LOG="$RUN_DIR/logs/refresh_spectre_runtime.log"
: > "$LOG"

: "${CADENCE_INSTALL_ROOT:=/projects/bics/cadence/installs}"
: "${IC_VERSION:=IC231}"
: "${IC_ROOT:=$CADENCE_INSTALL_ROOT/$IC_VERSION}"
: "${CADENCE_SEARCH_ROOT:=/projects/bics/cadence}"

choose_spectre_cmd() {
  local cand
  for cand in \
    "${SPECTRE_CMD:-}" \
    "$CADENCE_INSTALL_ROOT/SPECTRE231/tools/bin/spectre" \
    "$CADENCE_INSTALL_ROOT/SPECTRE231/bin/spectre" \
    "$CADENCE_INSTALL_ROOT/SPECTRE231/tools.lnx86/bin/spectre" \
    "$(command -v spectre 2>/dev/null || true)" \
    "$CADENCE_INSTALL_ROOT/SPECTRE231/tools.lnx86/spectre/bin/64bit/spectre"
  do
    if [[ -n "$cand" && -x "$cand" ]]; then
      printf '%s\n' "$cand"
      return 0
    fi
  done
  return 1
}

choose_export_launcher() {
  local cand
  for cand in \
    "${CADENCE_EXPORT_LAUNCHER:-}" \
    "$(command -v ocean 2>/dev/null || true)" \
    "$IC_ROOT/tools/bin/ocean" \
    "$IC_ROOT/bin/ocean" \
    "$IC_ROOT/tools.lnx86/dfII/bin/ocean" \
    "$IC_ROOT/tools.lnx86/dfII/bin/64bit/ocean" \
    "$(command -v virtuoso 2>/dev/null || true)" \
    "$IC_ROOT/tools/bin/virtuoso" \
    "$IC_ROOT/bin/virtuoso" \
    "$IC_ROOT/tools.lnx86/dfII/bin/virtuoso" \
    "$IC_ROOT/tools.lnx86/dfII/bin/64bit/virtuoso"
  do
    if [[ -n "$cand" && -x "$cand" ]]; then
      printf '%s\n' "$cand"
      return 0
    fi
  done
  return 1
}

write_spectre_env() {
  local spectre_cmd="$1"
  cat > "$RUN_DIR/support/spectre_runtime.env" <<EOF_ENV
# generated by refresh_spectre_runtime.sh at $(date -Is)
export CADENCE_INSTALL_ROOT="$CADENCE_INSTALL_ROOT"
export CADENCE_SEARCH_ROOT="$CADENCE_SEARCH_ROOT"
export SPECTRE_CMD="$spectre_cmd"
export PATH="$(dirname "$spectre_cmd"):\${PATH:-}"
EOF_ENV
}

# Resolve runtime libraries for any ELF launcher. This fixed the observed
# libvsacpp.so failure from the OCEAN/virtuoso export stage.
resolve_elf_runtime() {
  local exe="$1"
  local out_env="$2"
  local tag="$3"
  local dir_list="$RUN_DIR/support/${tag}_runtime_dirs.txt"
  : > "$dir_list"

  add_dir() {
    local d="$1"
    [[ -n "$d" && -d "$d" ]] || return 0
    printf '%s\n' "$d" >> "$dir_list"
  }
  make_ld() { awk '!seen[$0]++' "$dir_list" | paste -sd: -; }

  add_dir "$(dirname "$exe")"

  # High-probability Cadence runtime directories.
  while IFS= read -r d; do add_dir "$d"; done <<DIRS
$IC_ROOT/tools/bin
$IC_ROOT/bin
$IC_ROOT/tools/lib
$IC_ROOT/tools/lib/64bit
$IC_ROOT/tools.lnx86/lib
$IC_ROOT/tools.lnx86/lib/64bit
$IC_ROOT/tools.lnx86/dfII/lib
$IC_ROOT/tools.lnx86/dfII/lib/64bit
$IC_ROOT/tools/dfII/lib
$IC_ROOT/tools/dfII/lib/64bit
$CADENCE_INSTALL_ROOT/SPECTRE231/tools.lnx86/lib
$CADENCE_INSTALL_ROOT/SPECTRE231/tools.lnx86/lib/64bit
$CADENCE_INSTALL_ROOT/SPECTRE231/tools.lnx86/spectre/lib
$CADENCE_INSTALL_ROOT/SPECTRE231/tools.lnx86/spectre/lib/64bit
DIRS

  local pass missing lib found ld
  for pass in 1 2 3 4 5; do
    ld="$(make_ld)"
    export LD_LIBRARY_PATH="$ld:${LD_LIBRARY_PATH:-}"
    missing="$(ldd "$exe" 2>/dev/null | awk '/not found/{print $1}' | sort -u || true)"
    echo "[$tag] pass=$pass missing=$(echo "$missing" | tr '\n' ' ')" | tee -a "$LOG"
    [[ -z "$missing" ]] && break
    while IFS= read -r lib; do
      [[ -n "$lib" ]] || continue
      found="$(find "$CADENCE_SEARCH_ROOT" "$CADENCE_INSTALL_ROOT" -name "$lib" -type f -print -quit 2>/dev/null || true)"
      if [[ -n "$found" ]]; then
        echo "[$tag] found $lib at $found" | tee -a "$LOG"
        add_dir "$(dirname "$found")"
      else
        echo "[$tag] unresolved $lib" | tee -a "$LOG"
      fi
    done <<< "$missing"
  done

  ld="$(make_ld)"
  cat > "$out_env" <<EOF_ENV
# generated by refresh_spectre_runtime.sh at $(date -Is)
export CADENCE_INSTALL_ROOT="$CADENCE_INSTALL_ROOT"
export IC_VERSION="$IC_VERSION"
export IC_ROOT="$IC_ROOT"
export CADENCE_SEARCH_ROOT="$CADENCE_SEARCH_ROOT"
export CADENCE_EXPORT_LAUNCHER="${CADENCE_EXPORT_LAUNCHER:-}"
export PATH="$(dirname "$exe"):\${PATH:-}"
export LD_LIBRARY_PATH="$ld:\${LD_LIBRARY_PATH:-}"
EOF_ENV
}

SPECTRE_CHOSEN="$(choose_spectre_cmd || true)"
if [[ -z "$SPECTRE_CHOSEN" ]]; then
  echo "ERROR: could not find Spectre launcher/binary." | tee -a "$LOG" >&2
  exit 1
fi
echo "Using Spectre wrapper: $SPECTRE_CHOSEN" | tee -a "$LOG"
write_spectre_env "$SPECTRE_CHOSEN"

EXPORT_CHOSEN="$(choose_export_launcher || true)"
if [[ -z "$EXPORT_CHOSEN" ]]; then
  echo "WARNING: no ocean/virtuoso export launcher found. Spectre can run, but PSF export will fail." | tee -a "$LOG"
else
  echo "Using export launcher: $EXPORT_CHOSEN" | tee -a "$LOG"
  export CADENCE_EXPORT_LAUNCHER="$EXPORT_CHOSEN"
  resolve_elf_runtime "$EXPORT_CHOSEN" "$RUN_DIR/support/cadence_ic_runtime.env" "cadence_ic"
  # Insert actual launcher after writing the file.
  python3 - "$RUN_DIR/support/cadence_ic_runtime.env" "$EXPORT_CHOSEN" <<'PY'
import pathlib, sys
p = pathlib.Path(sys.argv[1])
launcher = sys.argv[2]
s = p.read_text()
s = s.replace('export CADENCE_EXPORT_LAUNCHER=""', f'export CADENCE_EXPORT_LAUNCHER="{launcher}"')
p.write_text(s)
PY
fi
